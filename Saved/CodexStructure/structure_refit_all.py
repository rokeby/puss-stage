"""Re-fit all six structure actors after the 28 Sep build (per-side slot fix,
c8aee3b), and save the level only. Run inside a conductor-granted level slot,
after a Backups/PreStructureRefit-* umap snapshot (the undo: generated geometry
cannot be regenerated by the old code, so the file backup is the revert).

Expected before: IsStructureCurrent FALSE for all six (the station signature
gained per-side extents). Expected after: TRUE for all six; slots per side start
under each side's own wing; every other count unchanged (gridiron, housings,
lines), because only slot starts moved. Refuses on any dirty state or stray ZZ_
actor. A read-only rehearsal: set STRUCTURE_REFIT_DRY_RUN via runpy.

SLOT COUNTS follow the mechanism, not a number (29 Sep, after this guard refused
on 186 -> 185): a side with no wing gets no slot under the per-side fix, where
the old code borrowed one from the other side's wing. So each structure's slot
count must fall by exactly its number of ONE-SIDED stations (one side's extent
0, the other's not), and the set of one-sided stations must equal
EXPECTED_ONE_SIDED, read before anything is touched. A new one-sided station
anywhere refuses, rather than being absorbed.
"""
import json
import os

import unreal

EXPECTED_WORLD = "/Game/InfinityStage/Dev/Maps/L_InfinityStage_V1VerticalSlice"
# Found 29 Sep: P05 Wing 004's Right panel stands on the route line (lateral 0).
EXPECTED_ONE_SIDED = {"Infinity Stage - Structure 05": ["P05 Wing 004"]}
OUT = os.path.join(unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_saved_dir()),
                   "CodexStructure", "structure_refit_all.json")
COUNTS = ("station_count", "cross_beam_count", "rail_segment_count", "board_count", "slot_count",
          "fixture_body_count", "hanging_line_count", "portal_piece_count")


def fail(message):
    raise RuntimeError(f"STRUCTURE_REFIT_FAILED|{message}")


def pk(p):
    s = str(p)
    return s.split("'")[1].split(".")[0] if "'" in s else s


def dirty():
    return ([pk(p) for p in unreal.EditorLoadingAndSavingUtils.get_dirty_content_packages()],
            [pk(p) for p in unreal.EditorLoadingAndSavingUtils.get_dirty_map_packages()])


ed = unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem)
world = ed.get_editor_world()
if not world or world.get_path_name().split(".", 1)[0] != EXPECTED_WORLD:
    fail("wrong project or world")
if ed.get_game_world() is not None:
    fail("PIE active")
if not hasattr(unreal, "InfinityStagePortalSettings"):
    fail("the loaded plugin predates the 28 Sep build (no portal settings) - stale binaries")
content0, maps0 = dirty()
if content0 or maps0:
    fail(f"editor already dirty: {content0} {maps0}")
sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
if any(a.get_actor_label().startswith("ZZ_") for a in sub.get_all_level_actors()):
    fail("stray ZZ_ actors in the level")

structures = sorted((a for a in sub.get_all_level_actors() if isinstance(a, unreal.InfinityStageStructureActor)),
                    key=lambda a: a.get_actor_label())
if len(structures) != 6:
    fail(f"expected 6 structure actors, found {len(structures)}")
before = {a.get_actor_label(): {"current": bool(a.is_structure_current()),
                                **{c: int(a.get_editor_property(c)) for c in COUNTS}} for a in structures}


def one_sided(actor):
    """Cue labels of the stations where exactly one side has a wing."""
    res = actor.gather_stations()
    stations = res[0] if isinstance(res, tuple) else res
    show = actor.get_editor_property("passage").get_editor_property("show_asset")
    labels = {unreal.GuidLibrary.conv_guid_to_string(c.get_editor_property("cue_guid")): str(c.get_editor_property("label"))
              for c in show.get_editor_property("cues")}
    out = []
    for st in stations:
        neg, pos = st.get_editor_property("negative_side_cm"), st.get_editor_property("positive_side_cm")
        if (neg <= 0.0) != (pos <= 0.0):
            g = unreal.GuidLibrary.conv_guid_to_string(st.get_editor_property("cue_guid"))
            out.append(labels.get(g, g))
    return sorted(out)


sided = {a.get_actor_label(): one_sided(a) for a in structures}
observed = {label: names for label, names in sided.items() if names}
if observed != {k: sorted(v) for k, v in EXPECTED_ONE_SIDED.items()}:
    fail(f"one-sided stations {observed} differ from EXPECTED_ONE_SIDED {EXPECTED_ONE_SIDED}")
# Slots are only cut where the ground layer is on and cuts slots.
slot_delta = {a.get_actor_label(): (-len(sided[a.get_actor_label()])
                                    if a.get_editor_property("ground").get_editor_property("enabled")
                                    and a.get_editor_property("ground").get_editor_property("cut_chariot_slots") else 0)
              for a in structures}
if globals().get("STRUCTURE_REFIT_DRY_RUN"):
    json.dump({"before": before, "one_sided": observed, "slot_delta": slot_delta}, open(OUT, "w"), indent=1)
    unreal.log(f"STRUCTURE_REFIT_DRY_RUN_OK|current_before={sum(v['current'] for v in before.values())}/6"
               f"|one_sided={observed}|slot_delta={ {k: v for k, v in slot_delta.items() if v} }|mutated=0")
    raise RuntimeError("STRUCTURE_REFIT_DRY_RUN_COMPLETE")

after = {}
for a in structures:
    if not a.materialize_structure():
        fail(f"{a.get_actor_label()} did not re-fit")
    after[a.get_actor_label()] = {"current": bool(a.is_structure_current()),
                                  **{c: int(a.get_editor_property(c)) for c in COUNTS}}
problems = []
for label, rec in after.items():
    if not rec["current"]:
        problems.append(f"{label} not current after re-fit")
    for c in COUNTS:
        # Only slot starts move, so boards change; slot COUNTS fall by exactly
        # the one-sided stations; everything else must be identical.
        if c == "board_count":
            continue
        want = before[label][c] + (slot_delta[label] if c == "slot_count" else 0)
        if rec[c] != want:
            problems.append(f"{label} {c}: {before[label][c]} -> {rec[c]} (expected {want})")
json.dump({"before": before, "after": after, "one_sided": observed, "slot_delta": slot_delta, "problems": problems},
          open(OUT, "w"), indent=1)
if problems:
    fail(f"unexpected changes, NOT saved: {problems}")
content1, maps1 = dirty()
if content1 or maps1 != [EXPECTED_WORLD]:
    fail(f"unexpected dirty set before save: {content1} {maps1}")
if not unreal.get_editor_subsystem(unreal.LevelEditorSubsystem).save_current_level():
    fail("level save failed")
content2, maps2 = dirty()
unreal.log(f"STRUCTURE_REFIT_OK|current={sum(v['current'] for v in after.values())}/6"
           f"|boards={sum(v['board_count'] for v in before.values())}->{sum(v['board_count'] for v in after.values())}"
           f"|level_saved=1|dirty_after={len(content2)}+{len(maps2)}")
